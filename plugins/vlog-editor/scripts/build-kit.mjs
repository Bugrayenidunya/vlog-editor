#!/usr/bin/env node
// Build the final brand kit from a brand.json.
//
//   node build-kit.mjs --brand brands/<slug> [--from brands/<slug>/directions/A/brand.json]
//                      [--footage <video>] [--no-sizzle] [--no-logos]
//
// Writes into brands/<slug>/:
//   brand.json            the source of truth (copied from --from when given)
//   DESIGN.md             HyperFrames design spec: frontmatter tokens (normative) + guidelines (intent)
//   tokens.css            @font-face + CSS variables + caption/logo styles for any web use
//   fonts/                local .woff2 + fonts.css + fonts.json (licenses)
//   components/           brand-hook / brand-captions / brand-lower-third / brand-end-card (.html sub-compositions)
//   logo/                 avatar.png (1080², profile picture), wordmark.png
//   preview/              board.png, sizzle.mp4 (the kit applied to a real HyperFrames project and rendered)
//   kit.json              build manifest with validation issues
import fsp from "node:fs/promises";
import path from "node:path";
import { parseArgs, log, die, exists, ensureDir, writeJson, readJson, runHf, warmHf, run } from "./lib/util.mjs";
import { loadBrand, validateBrand, fontFamilies, cssVariables, captionCss, logoCss, emphasize } from "./lib/brand.mjs";
import { hookComponent, captionsComponent, lowerThirdComponent, endCardComponent, logoStillHtml, defaultWords } from "./lib/components.mjs";
import { fetchFonts } from "./fonts.mjs";
import { prepareBoard, snapshotBoard } from "./board.mjs";
import { applyBrand } from "./apply-brand.mjs";

const args = parseArgs();
if (!args.brand) die("usage: build-kit.mjs --brand brands/<slug> [--from <direction brand.json>] [--footage video] [--no-sizzle] [--no-logos]");
const brandDir = path.resolve(args.brand);
const rel = (p) => path.relative(process.cwd(), p);
await ensureDir(brandDir);
if (args.from) {
  const src = await readJson(path.resolve(args.from));
  const prev = await readJson(path.join(brandDir, "brand.json"), null);
  src.version = (prev?.version || 0) + 1;
  src.builtFrom = path.relative(brandDir, path.resolve(args.from));
  await writeJson(path.join(brandDir, "brand.json"), src);
}
const brandFile = path.join(brandDir, "brand.json");
if (!exists(brandFile)) die(`no brand.json in ${brandDir} (pass --from <direction>/brand.json)`);
const b = await loadBrand(brandFile);
const issues = validateBrand(b);
const work = await ensureDir(path.join(brandDir, ".work"));
const cacheDir = path.join(path.dirname(brandDir), ".cache", "fonts");
await warmHf(brandDir);

// ---------- fonts + tokens ----------
log("→ fonts");
const fonts = await fetchFonts({ families: fontFamilies(b), outDir: path.join(brandDir, "fonts"), urlPrefix: "", cacheDir });
for (const m of fonts.missing) issues.push({ level: "error", msg: `font ${m.family}: ${m.reason}` });
const fontsCssFor = (prefix) => fonts.css.replace(/url\("([^"]+)"\)/g, (m, f) => `url("${prefix}${f}")`);
await fsp.writeFile(
  path.join(brandDir, "tokens.css"),
  `/* ${b.name} — brand tokens (generated by vlog-editor build-kit; edit brand.json, not this file) */\n${fontsCssFor("fonts/")}\n:root {\n${cssVariables(b)}\n}\n\n${captionCss()}\n\n${logoCss()}\n`,
);

// ---------- components ----------
log("→ components");
const compDir = await ensureDir(path.join(brandDir, "components"));
const compFonts = fontsCssFor("assets/fonts/").replace(/^/gm, "    ");
const components = {
  "brand-hook.html": hookComponent(b, compFonts),
  "brand-captions.html": captionsComponent(b, compFonts),
  "brand-lower-third.html": lowerThirdComponent(b, compFonts),
  "brand-end-card.html": endCardComponent(b, compFonts),
};
for (const [f, html] of Object.entries(components)) await fsp.writeFile(path.join(compDir, f), html);

// ---------- DESIGN.md ----------
function yaml(value, indent = 0) {
  const pad = " ".repeat(indent);
  const scalar = (v) => (typeof v === "number" || typeof v === "boolean" ? String(v) : v == null ? "null" : JSON.stringify(String(v)));
  if (Array.isArray(value)) return value.length ? value.map((v) => (typeof v === "object" && v ? `${pad}-\n${yaml(v, indent + 2)}` : `${pad}- ${scalar(v)}`)).join("\n") : `${pad}[]`;
  return Object.entries(value)
    .filter(([, v]) => v !== undefined)
    .map(([k, v]) => {
      if (v && typeof v === "object") {
        if (Array.isArray(v) && v.every((x) => typeof x !== "object")) return `${pad}${k}: [${v.map(scalar).join(", ")}]`;
        return `${pad}${k}:\n${yaml(v, indent + 2)}`;
      }
      return `${pad}${k}: ${scalar(v)}`;
    })
    .join("\n");
}
const list = (xs) => [].concat(xs || []).filter(Boolean);
const bullets = (xs) => list(xs).map((x) => `- ${x}`).join("\n") || "- —";
const f = b.fonts;
const up = (t) => t === "uppercase";
const front = {
  version: "alpha",
  name: `${b.name} — Brand (vertical video)`,
  description: [b.tagline, b.positioning].filter(Boolean).join(" ") || `${b.name} brand kit`,
  unit: "the frame — 1080×1920 (TikTok, Instagram Reels, YouTube Shorts)",
  principle: b.direction?.rationale || b.direction?.summary || "one hook, one subject, captions always",
  colors: {
    ground: b.colors.ground,
    surface: b.colors.surface,
    ink: b.colors.ink,
    muted: b.colors.muted,
    primary: b.colors.primary,
    accent: b.colors.accent,
    highlight: b.colors.highlight,
    "on-primary": b.derived.onPrimary,
    "on-accent": b.derived.onAccent,
    "caption-text": b.colors.captionText,
    "caption-stroke": b.colors.captionStroke,
    "caption-box": b.colors.captionBox,
  },
  typography: {
    "hook-title": { fontFamily: f.display.family, px: "76–150 (fit to 3 lines)", weight: Math.max(...list(f.display.weights)), lineHeight: f.display.lineHeight ?? 1, tracking: f.display.tracking || "0", upper: up(f.display.transform) },
    caption: { fontFamily: f.caption.family, px: b.captions.size, minPx: b.captions.minSize, weight: f.caption.weight, upper: up(f.caption.transform), tracking: f.caption.tracking || "0" },
    "lower-third-title": { fontFamily: f.display.family, px: 62, weight: Math.max(...list(f.display.weights)), upper: up(f.display.transform) },
    "lower-third-sub": { fontFamily: f.body.family, px: 30, weight: 700 },
    "end-card-cta": { fontFamily: f.display.family, px: 92, weight: Math.max(...list(f.display.weights)), upper: up(f.display.transform) },
    body: { fontFamily: f.body.family, px: 36, weight: Math.min(...list(f.body.weights)), lineHeight: f.body.lineHeight ?? 1.25 },
  },
  spacing: {
    "safe-top": `${b.layout.safeTop}px`,
    "text-band": `${b.layout.safeTop}–${b.layout.textBottom}px`,
    "rail-right": `${b.layout.railRight}px`,
    "pad-x": `${b.layout.padX}px`,
    "caption-bottom": `${b.layout.captionBottom}px`,
  },
  components: {
    captions: { file: "compositions/brand/brand-captions.html", style: b.captions.style, wordsPerGroup: list(b.captions.wordsPerGroup).join("–"), description: "Mount once on a host with data-track-kind=\"captions\"; fill WORDS between the @words markers from transcript.json." },
    "hook-title": { file: "compositions/brand/brand-hook.html", variables: "hook, emphasis", description: "On screen at frame 0 (the thumbnail); first 2–3 s." },
    "lower-third": { file: "compositions/brand/brand-lower-third.html", variables: "title, subtitle", description: "Place or topic chip at y 930, above the caption band." },
    "end-card": { file: "compositions/brand/brand-end-card.html", variables: "cta, handle", description: "Last 2–3 s: logo, call to action, handle." },
    logo: { style: b.logo.style, text: b.logo.text, monogram: b.logo.monogram, files: "assets/brand/avatar.png, assets/brand/wordmark.png" },
  },
  motion: { energy: b.motion.energy, ease: b.motion.ease, durations: b.motion.durations, transitions: list(b.motion.transitions), "shot-seconds": list(b.motion.pace?.shotSeconds), "first-cut-by": b.motion.pace?.firstCutBy ?? null },
  look: b.look,
};
if (b.sound?.enabled) front.sound = b.sound;
const design = `---
${yaml(front)}
---

# ${b.name} — Brand

## Overview

${[b.tagline && `**${b.tagline}.**`, b.positioning, b.niche && `Niche: ${b.niche}.`, b.audience && `Audience: ${b.audience}.`].filter(Boolean).join(" ") || "—"}

Personality: ${Object.entries(b.personality || {}).map(([k, v]) => `${k} ${typeof v === "number" ? Math.round(v * 10) + "/10" : v}`).join(" · ") || "—"}. Languages: ${list(b.languages).join(", ")}.

## Colors

The ground is \`${b.colors.ground}\` with \`${b.colors.ink}\` ink. \`${b.colors.primary}\` (primary) carries brand surfaces and the logo mark; \`${b.colors.accent}\` (accent) is for small marks, bars and dots; \`${b.colors.highlight}\` (highlight) marks the one word that matters — in hook titles and on the spoken caption word. Over footage, text sits on footage with a shadow or on a brand surface; never put long text on the highlight colour.

## Typography

**${f.display.family}** for hooks, titles and the call to action${up(f.display.transform) ? ", always uppercase" : ""}. **${f.body.family}** for everything read in passing (handles, subtitles, labels). Captions use **${f.caption.family} ${f.caption.weight}**${up(f.caption.transform) ? ", uppercase" : ""}. Nothing meant to be read under 28 px; hooks are cut to fit three lines, never shrunk below 76 px.

## Captions

Style **${b.captions.style}**, ${list(b.captions.wordsPerGroup).join("–")} words per group, one group at a time, bottom edge ${b.layout.captionBottom} px from the frame bottom, clear of the right-hand action rail. Speech is always captioned: many viewers watch muted.

## Motion and editing

${b.motion.energy} energy. Shots of ${list(b.motion.pace?.shotSeconds).join("–")} s; the first cut lands by ${b.motion.pace?.firstCutBy ?? "—"} s. Transitions: ${list(b.motion.transitions).join(", ")}. Eases: enter \`${b.motion.ease.enter}\`, exit \`${b.motion.ease.exit}\`, pop \`${b.motion.ease.pop}\`. Frame 0 is the thumbnail and the hook: a face, the result, or the hook title already on screen — never black, never the logo.

## Look

${b.look?.grade ? `Grade: **${b.look.grade}**.` : ""} ${["luma", "contrast", "saturation", "warmth"].filter((k) => b.look?.[k] != null).map((k) => `${k} ≈ ${b.look[k]}`).join(", ")}${["luma", "contrast", "saturation", "warmth"].some((k) => b.look?.[k] != null) ? " (targets measured with `npx hyperframes measure look`)." : ""} Apply grades with \`npx hyperframes media-treatment\`, never CSS filters.
${b.sound?.enabled ? `
## Sound

Music: ${list(b.sound.music?.moods).join(", ")} ${list(b.sound.music?.genres).join(" / ")}${b.sound.music?.bpm ? `, ${list(b.sound.music.bpm).join("–")} BPM` : ""}, ${b.sound.music?.vocals || "instrumental"}, mixed to ${b.sound.music?.lufs ?? -14} LUFS. ${b.sound.sting?.description ? `Sting: ${b.sound.sting.description}.` : ""} Source music and effects with \`/media-use\`; cut on the beat (\`npx hyperframes beats\`).
` : ""}
## Voice

Tone: ${list(b.voice?.tone).join(", ") || "—"}.

Hook formulas:
${bullets(b.voice?.hookFormulas)}

Calls to action:
${bullets(b.voice?.ctas)}

Hashtags: ${list(b.voice?.hashtags).join(" ") || "—"}

## Do

${bullets(b.rules?.do)}

## Don't

${bullets(b.rules?.dont)}
${b.evidence?.summary ? `
## Evidence

${bullets(b.evidence.summary)}
${b.evidence.styleDna ? `\nFull analysis: \`${b.evidence.styleDna}\`.` : ""}
` : ""}`;
await fsp.writeFile(path.join(brandDir, "DESIGN.md"), design);

// ---------- logos ----------
const logos = {};
if (!args["no-logos"]) {
  log("→ logos");
  const logoDir = await ensureDir(path.join(brandDir, "logo"));
  for (const kind of ["avatar", "wordmark"]) {
    const dir = path.join(work, `logo-${kind}`);
    await fsp.rm(dir, { recursive: true, force: true });
    await ensureDir(path.join(dir, "assets", "fonts"));
    for (const fl of await fsp.readdir(path.join(brandDir, "fonts"))) if (fl.endsWith(".woff2")) await fsp.copyFile(path.join(brandDir, "fonts", fl), path.join(dir, "assets", "fonts", fl));
    await fsp.writeFile(path.join(dir, "index.html"), logoStillHtml(b, fontsCssFor("assets/fonts/").replace(/^/gm, "      "), kind));
    try {
      logos[kind] = rel(await snapshotBoard(dir, path.join(logoDir, `${kind}.png`)));
    } catch (e) {
      issues.push({ level: "warn", msg: `logo ${kind}: ${e.message}` });
    }
  }
}

// ---------- preview: board + sizzle ----------
const preview = {};
const previewDir = await ensureDir(path.join(brandDir, "preview"));
log("→ board");
try {
  const tmpBrand = path.join(work, "board-final", "brand.json");
  await writeJson(tmpBrand, { ...(await readJson(brandFile)), direction: { id: "★", label: b.name, summary: b.tagline || b.direction?.summary || "" } });
  const prep = await prepareBoard(tmpBrand, { cacheDir });
  preview.board = rel(await snapshotBoard(prep.dir, path.join(previewDir, "board.png")));
} catch (e) {
  issues.push({ level: "warn", msg: `board: ${e.message}` });
}

if (!args["no-sizzle"]) {
  log("→ sizzle (apply kit to a project and render)");
  const proj = path.join(work, "sizzle");
  await fsp.rm(proj, { recursive: true, force: true });
  await applyBrand(brandDir, proj, { force: true });
  let footage = "";
  if (args.footage && exists(path.resolve(args.footage))) {
    await run("ffmpeg", ["-v", "error", "-y", "-i", path.resolve(args.footage), "-t", "9", "-an", "-vf", "scale=1080:1920:force_original_aspect_ratio=increase,crop=1080:1920,fps=30", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "20", path.join(proj, "assets", "footage.mp4")]);
    footage = `<video id="footage" class="clip" src="assets/footage.mp4" data-start="0" data-duration="6.6" data-track-index="0" muted playsinline></video>`;
  }
  // The sizzle's captions use the sample line with even timings.
  const capFile = path.join(proj, "compositions", "brand", "brand-captions.html");
  const capHtml = await fsp.readFile(capFile, "utf8");
  await fsp.writeFile(capFile, capHtml.replace(/(\/\/ @words-start[^\n]*\n\s*var WORDS = )[^\n]*(\n)/, `$1${JSON.stringify(defaultWords(b.samples.caption, 0.2, 0.34))};$2`));
  const host = (id, start, dur, track, values, kind = "graphics") =>
    `<div id="${id}" data-composition-id="${id}" data-composition-src="compositions/brand/${id}.html" data-start="${start}" data-duration="${dur}" data-track-index="${track}" data-track-kind="${kind}" data-width="1080" data-height="1920"${values ? ` data-variable-values='${JSON.stringify(values).replace(/'/g, "&#39;")}'` : ""}></div>`;
  const handle = b.handles?.tiktok || b.handles?.instagram || b.handles?.youtube || "";
  await fsp.writeFile(
    path.join(proj, "index.html"),
    `<!doctype html>
<html lang="${(b.languages || ["en"])[0]}">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
    <style>
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { width: 1080px; height: 1920px; overflow: hidden; background: ${b.colors.ground}; }
      #backdrop { position: absolute; inset: 0; background: ${b.colors.ground}; overflow: hidden; }
      #glow-a, #glow-b { position: absolute; width: 1400px; height: 1400px; border-radius: 50%; }
      #glow-a { left: -300px; top: -400px; background: radial-gradient(closest-side, color-mix(in srgb, ${b.colors.primary} 45%, transparent), transparent); }
      #glow-b { left: 100px; top: 900px; background: radial-gradient(closest-side, color-mix(in srgb, ${b.colors.accent} 26%, transparent), transparent); }
      #footage { position: absolute; inset: 0; width: 100%; height: 100%; object-fit: cover; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="9" data-width="1080" data-height="1920">
      <div id="backdrop"><div id="glow-a"></div><div id="glow-b"></div></div>
      ${footage}
      ${host("brand-hook", 0, 2.8, 2, { hook: b.samples.hook, emphasis: b.samples.hookEmphasis || "" })}
      ${host("brand-captions", 2.8, 3.8, 3, null, "captions")}
      ${host("brand-lower-third", 3.0, 3.4, 4, { title: b.samples.lowerThird?.title || "", subtitle: b.samples.lowerThird?.subtitle || "" })}
      ${host("brand-end-card", 6.6, 2.4, 5, { cta: b.samples.cta || "", handle })}
    </div>
    <script>
      window.__timelines = window.__timelines || {};
      const tl = gsap.timeline({ paused: true });
      tl.fromTo("#glow-a", { x: 0, y: 0 }, { x: 260, y: 180, duration: 9, ease: "sine.inOut" }, 0);
      tl.fromTo("#glow-b", { x: 0, y: 0 }, { x: -220, y: -260, duration: 9, ease: "sine.inOut" }, 0);
      window.__timelines["main"] = tl;
    </script>
  </body>
</html>
`,
  );
  const check = await runHf(["check", "--json"], { cwd: proj, timeoutMs: 300000, workspace: proj });
  const checkJson = (() => {
    try {
      return JSON.parse(check.stdout.slice(check.stdout.indexOf("{")));
    } catch {
      return null;
    }
  })();
  preview.check = checkJson ? { ok: checkJson.ok, errors: checkJson.errorCount ?? checkJson.errors?.length, warnings: checkJson.warningCount ?? checkJson.warnings?.length } : { raw: check.stdout.slice(-400) };
  const out = path.join(previewDir, "sizzle.mp4");
  const r = await runHf(["render", "-o", out, "--quiet"], { cwd: proj, timeoutMs: 900000, workspace: proj });
  if (exists(out)) preview.sizzle = rel(out);
  else issues.push({ level: "warn", msg: `sizzle render failed: ${(r.stderr || r.stdout).trim().split("\n").slice(-3).join(" ")}` });
  preview.project = rel(proj);
}

const kit = { schema: "vlog-editor/kit@1", brand: b.name, version: b.version || 1, builtAt: new Date().toISOString(), files: { design: "DESIGN.md", tokens: "tokens.css", fonts: fonts.families.map((x) => ({ family: x.family, weights: x.weights, latinExt: x.latinExt, license: x.license })), components: Object.keys(components).map((x) => `components/${x}`), logos, preview }, issues };
await writeJson(path.join(brandDir, "kit.json"), kit);
process.stdout.write(JSON.stringify({ ok: !issues.some((i) => i.level === "error"), brand: rel(brandDir), ...kit }, null, 2) + "\n");
